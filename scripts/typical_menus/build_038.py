# Generates supabase/sql/038_typical_menus.sql from supabase/data/typical/typical_menus.json (#103).
# Edit the JSON, then run:  python scripts/typical_menus/build_038.py
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / 'supabase/data/typical/typical_menus.json'
OUT = ROOT / 'supabase/sql/038_typical_menus.sql'
VOCAB = ['pork', 'beef', 'chicken', 'lamb', 'seafood', 'egg', 'dairy', 'alcohol', 'peanut', 'wheat', 'soy']

data = json.loads(SRC.read_text(encoding='utf-8'))
lines = []
w = lines.append


def q(text):
    return "'" + str(text).replace("'", "''") + "'"


def arr(items):
    for item in items:
        assert item in VOCAB, item
    return q('{' + ','.join(items) + '}') + '::text[]'


menus = data['menus']
dish_count = sum(len(m['dishes']) for m in menus)
w('-- 038_typical_menus.sql')
w('-- GENERATED by scripts/typical_menus/build_038.py from supabase/data/typical/typical_menus.json - edit the JSON, then re-run the script.')
w('--')
w('-- Part of #103. Typical menus: for each type of restaurant, the dishes it usually serves and the ingredients')
w('-- those dishes usually have. This is GENERATED data (allowed by our lecturer), not any restaurant\'s menu.')
w(f'-- {len(menus)} menus, {dish_count} dishes. Types too mixed for one honest menu keep only the food-type hint:')
w('-- ' + data['_not_covered'])
w('--')
w('-- How it stays honest:')
w('--   * dishes.typical marks every generated dish; the app labels the menu "Typical menu for <type>" and never')
w('--     shows a typical dish as Safe to anyone with a diet or allergy (Ask first at best). No prices (0 = hidden).')
w('--   * apply_typical_menus() only fills restaurants with NO dishes at all, so run it after the chain menus (037).')
w('--   * As soon as a restaurant gets any real dish (menu photo approval, owner, chain), a trigger deletes its')
w('--     typical dishes, so real and typical never mix.')
w('-- After reviewing, run:  select * from public.apply_typical_menus();')
w('-- Undo everything:      delete from public.dishes where typical;')
w('-- Safe to re-run.')
w('')
w('begin;')
w('')
w('alter table public.dishes add column if not exists typical boolean not null default false;')
w('create index if not exists dishes_typical_idx on public.dishes (restaurant_id) where typical;')
w('')
w('-- Team-only source tables (RLS on, no policies): the app never reads them, only the copied dishes.')
w('create table if not exists public.typical_menus (')
w('  id text primary key,')
w('  name_ko text not null,')
w('  name_en text not null,')
w("  categories text[] not null check (cardinality(categories) > 0)  -- restaurants.category values")
w(');')
w('create table if not exists public.typical_menu_dishes (')
w('  menu_id text not null references public.typical_menus (id) on delete cascade,')
w('  sort integer not null,')
w('  name_ko text not null,')
w('  name_en text not null,')
w("  contains text[] not null default '{}',")
w("  may_contain text[] not null default '{}',")
w('  primary key (menu_id, sort)')
w(');')
w('alter table public.typical_menus enable row level security;')
w('alter table public.typical_menu_dishes enable row level security;')
w('revoke all on public.typical_menus, public.typical_menu_dishes from anon, authenticated;')
w('')
w('-- Refill the source tables from the JSON (re-run safe).')
w('delete from public.typical_menus;')
w('insert into public.typical_menus (id, name_ko, name_en, categories) values')
w(',\n'.join(f"  ({q(m['id'])}, {q(m['name_ko'])}, {q(m['name_en'])}, {arr_cat})" for m in menus
            for arr_cat in [q('{' + ','.join(m['categories']) + '}') + '::text[]']) + ';')
w('insert into public.typical_menu_dishes (menu_id, sort, name_ko, name_en, contains, may_contain) values')
rows = []
for m in menus:
    for i, (ko, en, contains, may) in enumerate(m['dishes'], start=1):
        assert not set(contains) & set(may), (m['id'], ko)
        rows.append(f"  ({q(m['id'])}, {i}, {q(ko)}, {q(en)}, {arr(contains)}, {arr(may)})")
w(',\n'.join(rows) + ';')
w('')
w('-- Copies a typical menu to every restaurant of its type that has no dishes yet.')
w('create or replace function public.apply_typical_menus()')
w('returns table (menu_id text, restaurants_filled bigint, dishes_added bigint)')
w('language plpgsql')
w("set search_path = ''")
w('as $$')
w('begin')
w('  return query')
w('  with empty as (')
w('    select r.id, r.category from public.restaurants r')
w('    where not exists (select 1 from public.dishes d where d.restaurant_id = r.id)')
w('  ), added as (')
w('    insert into public.dishes')
w('      (id, restaurant_id, name_ko, name_en, price_won, contains, may_contain, verified_count, last_checked, typical)')
w("    select e.id || '-typical-' || m.id || '-' || lpad(td.sort::text, 2, '0'), e.id, td.name_ko, td.name_en,")
w('           0, td.contains, td.may_contain, 0, null, true')
w('    from empty e')
w('    join public.typical_menus m on e.category = any (m.categories)')
w('    join public.typical_menu_dishes td on td.menu_id = m.id')
w('    on conflict (id) do nothing')
w('    returning restaurant_id, id')
w('  )')
w("  select regexp_replace(split_part(a.id, '-typical-', 2), '-[0-9]+$', '') as menu_id,")
w('         count(distinct a.restaurant_id), count(*)')
w('  from added a group by 1 order by 1;')
w('end;')
w('$$;')
w('revoke execute on function public.apply_typical_menus() from public, anon, authenticated;')
w('')
w('-- A real dish replaces the typical menu: when a restaurant gets any non-typical dish, its typical dishes go.')
w('create or replace function public.drop_typical_when_real()')
w('returns trigger')
w('language plpgsql')
w('security definer')
w("set search_path = ''")
w('as $$')
w('begin')
w('  delete from public.dishes where restaurant_id = new.restaurant_id and typical;')
w('  return null;')
w('end;')
w('$$;')
w('revoke execute on function public.drop_typical_when_real() from public, anon, authenticated;')
w('drop trigger if exists dishes_drop_typical_when_real on public.dishes;')
w('create trigger dishes_drop_typical_when_real')
w('  after insert on public.dishes')
w('  for each row when (not new.typical)')
w('  execute function public.drop_typical_when_real();')
w('')
w('commit;')
w('')
w('-- Check:')
w('-- select count(*) filter (where typical) as typical_dishes, count(distinct restaurant_id) filter (where typical) as restaurants from public.dishes;')
OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'wrote {OUT.relative_to(ROOT)}: {len(menus)} menus, {dish_count} dishes')
