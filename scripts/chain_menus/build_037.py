"""Build supabase/sql/037_chain_menus.sql from supabase/data/chains/*.json.

Run from the repo root:  python scripts/chain_menus/build_037.py
Re-run it whenever a chain file changes; the SQL is generated, don't edit it by hand.
"""
import glob
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
DATA = os.path.join(ROOT, 'supabase', 'data', 'chains')
OUT = os.path.join(ROOT, 'supabase', 'sql', '037_chain_menus.sql')
VOCAB = {'pork', 'beef', 'chicken', 'lamb', 'seafood', 'egg', 'dairy', 'alcohol', 'peanut', 'wheat', 'soy'}


def q(s):
    """SQL string literal (or null)."""
    if s is None:
        return 'null'
    return "'" + str(s).replace("'", "''") + "'"


def arr(xs):
    """SQL text[] literal."""
    return q('{' + ','.join('"' + x.replace('\\', '\\\\').replace('"', '\\"') + '"' for x in xs) + '}') + '::text[]'


def chain_id(path):
    return os.path.splitext(os.path.basename(path))[0]


chains, dishes, problems = [], [], []
for path in sorted(glob.glob(os.path.join(DATA, '*.json'))):
    cid = chain_id(path)
    d = json.load(open(path, encoding='utf-8'))
    has_allergens = any(x['allergens_as_written'] != 'not shown' for x in d['dishes'])
    chains.append((cid, d, has_allergens))
    for n, x in enumerate(d['dishes'], 1):
        bad = (set(x['contains']) | set(x['may_contain'])) - VOCAB
        if bad:
            problems.append(f'{cid} #{n} {x["name_ko"]}: unknown tag {bad}')
        if set(x['contains']) & set(x['may_contain']):
            problems.append(f'{cid} #{n} {x["name_ko"]}: tag in both contains and may_contain')
        dishes.append((cid, n, x))
if problems:
    sys.exit('Fix the chain files first:\n' + '\n'.join(problems))

with_data = [c for c in chains if c[2]]
menu_only = [c for c in chains if not c[2]]
L = []
w = L.append
w('-- 037_chain_menus.sql')
w('-- GENERATED by scripts/chain_menus/build_037.py from supabase/data/chains/*.json - edit the JSON, then re-run the script.')
w('--')
w('-- Official chain menus for franchise branches in 안산 (033/034 imported them with no menu).')
w(f'-- {len(chains)} chains, {len(dishes)} dishes, all collected on 2026-11-24 from each chain\'s own website')
w('-- (menu pages, 알레르기 / 원산지 pages). Screenshots of every allergen table: supabase/data/chains/evidence/.')
w(f'-- With official allergen data ({len(with_data)}): ' + ', '.join(c[1]['chain_ko'] for c in with_data) + '.')
w(f'-- Menu only, no allergen data published ({len(menu_only)}): ' + ', '.join(c[1]['chain_ko'] for c in menu_only) + '.')
w('--')
w('-- What this file does: creates two team-only tables (chain_menus, chain_menu_dishes), fills them, and adds')
w('-- apply_chain_menus(). It does NOT touch restaurants or dishes. After reviewing, run:')
w('--     select * from public.apply_chain_menus();            -- every chain with allergen data')
w("--     select * from public.apply_chain_menus('momstouch'); -- one chain")
w('-- apply_chain_menus() copies a chain\'s dishes to every restaurant whose name_ko matches the chain\'s')
w('-- name_patterns (ILIKE) and none of its name_exclude, and that has NO dishes yet (real menus are never')
w("-- overwritten). Menu-only chains are refused, and single dishes marked 'not shown' are skipped:")
w("-- empty tags would make them look safe. The app hides a price of 0.")
w('-- Missing prices are stored as 0 (dishes.price_won is not null).')
w("-- Undo: delete from public.dishes where id like '%-chain-%';")
w('-- Safe to re-run.')
w('')
w('begin;')
w('')
w('-- ---------- tables ----------')
w('create table if not exists public.chain_menus (')
w('  chain_id text primary key,                 -- file name, e.g. momstouch')
w('  chain_ko text not null,')
w('  chain_en text not null,')
w("  name_patterns text[] not null,            -- ILIKE patterns for restaurants.name_ko, e.g. '%맘스터치%'")
w("  name_exclude text[] not null default '{}', -- ILIKE patterns that must NOT match (e.g. a kebab shop called BBQ)")
w('  has_allergen_data boolean not null,')
w("  source_urls text[] not null default '{}',")
w('  checked_on date not null,')
w("  notes text not null default ''")
w(');')
w('create table if not exists public.chain_menu_dishes (')
w('  chain_id text not null references public.chain_menus (chain_id) on delete cascade,')
w('  dish_no int not null,')
w('  name_ko text not null,')
w('  name_en text not null,')
w('  price_won int,                             -- null = not shown on the official site')
w("  contains text[] not null default '{}'")
w("    check (contains <@ '{pork,beef,chicken,lamb,seafood,egg,dairy,alcohol,peanut,wheat,soy}'::text[]),")
w("  may_contain text[] not null default '{}'")
w("    check (may_contain <@ '{pork,beef,chicken,lamb,seafood,egg,dairy,alcohol,peanut,wheat,soy}'::text[]),")
w("  allergens_as_written text not null,       -- the official wording, or 'not shown'")
w('  source_url text not null,')
w('  primary key (chain_id, dish_no),')
w('  check (not (contains && may_contain))')
w(');')
w('-- Team only (like 013): RLS on, no policies, so the app cannot read or write these.')
w('alter table public.chain_menus enable row level security;')
w('alter table public.chain_menu_dishes enable row level security;')
w('')
w('-- ---------- data ----------')
w('-- Re-running replaces the stored chain data with the current files.')
w('delete from public.chain_menu_dishes;')
w('delete from public.chain_menus;')
w('')
w('insert into public.chain_menus')
w('  (chain_id, chain_ko, chain_en, name_patterns, name_exclude, has_allergen_data, source_urls, checked_on, notes)')
w('values')
rows = []
for cid, d, has in chains:
    rows.append(f"  ({q(cid)}, {q(d['chain_ko'])}, {q(d['chain_en'])}, {arr(d['name_patterns'])}, "
                f"{arr(d.get('name_exclude', []))}, {'true' if has else 'false'}, {arr(d['source_urls'])}, "
                f"{q(d['checked_on'])}, {q(d['notes'])})")
w(',\n'.join(rows) + ';')
w('')
for cid, d, _ in chains:
    w(f'-- {d["chain_ko"]} ({cid})')
    w('insert into public.chain_menu_dishes')
    w('  (chain_id, dish_no, name_ko, name_en, price_won, contains, may_contain, allergens_as_written, source_url)')
    w('values')
    rows = [f"  ({q(cid)}, {n}, {q(x['name_ko'])}, {q(x['name_en'])}, "
            f"{x['price_won'] if x['price_won'] else 'null'}, {arr(x['contains'])}, {arr(x['may_contain'])}, "
            f"{q(x['allergens_as_written'])}, {q(x['source_url'])})"
            for c2, n, x in dishes if c2 == cid]
    w(',\n'.join(rows) + ';')
    w('')
w('-- ---------- apply_chain_menus ----------')
w('create or replace function public.apply_chain_menus(p_chain text default null)')
w('returns table (chain_id text, restaurants_matched int, restaurants_filled int, dishes_added int)')
w('language plpgsql')
w('as $$')
w('#variable_conflict use_column')
w('declare')
w('  c record;')
w('  v_matched int;')
w('  v_filled int;')
w('  v_dishes int;')
w('begin')
w('  if p_chain is not null and not exists (select 1 from public.chain_menus m where m.chain_id = p_chain) then')
w("    raise exception 'unknown chain %', p_chain;")
w('  end if;')
w('  if p_chain is not null and not (select m.has_allergen_data from public.chain_menus m where m.chain_id = p_chain) then')
w("    raise exception 'chain % has no official allergen data; its dishes would all look safe', p_chain;")
w('  end if;')
w('')
w('  for c in')
w('    select m.* from public.chain_menus m')
w('    where m.has_allergen_data and (p_chain is null or m.chain_id = p_chain)')
w('    order by m.chain_id')
w('  loop')
w('    create temporary table if not exists _chain_targets (restaurant_id text primary key) on commit drop;')
w('    truncate _chain_targets;')
w('')
w('    insert into _chain_targets (restaurant_id)')
w('    select r.id from public.restaurants r')
w('    where r.name_ko ilike any (c.name_patterns)')
w('      and not (r.name_ko ilike any (c.name_exclude));')
w('    get diagnostics v_matched = row_count;')
w('')
w('    -- keep only restaurants that have no dishes yet')
w('    delete from _chain_targets t where exists (select 1 from public.dishes d where d.restaurant_id = t.restaurant_id);')
w('    select count(*) into v_filled from _chain_targets;')
w('')
w('    insert into public.dishes')
w('      (id, restaurant_id, name_ko, name_en, price_won, contains, may_contain, verified_count, last_checked)')
w("    select t.restaurant_id || '-chain-' || c.chain_id || '-' || cd.dish_no,")
w('           t.restaurant_id, cd.name_ko, cd.name_en, coalesce(cd.price_won, 0),')
w('           cd.contains, cd.may_contain, 0, c.checked_on')
w('    from _chain_targets t')
w('    cross join public.chain_menu_dishes cd')
w('    where cd.chain_id = c.chain_id')
w("      -- a dish without official allergen info would look Safe (empty tags), so it is left out")
w("      and cd.allergens_as_written <> 'not shown'")
w('    on conflict (id) do nothing;')
w('    get diagnostics v_dishes = row_count;')
w('')
w("    update public.restaurants r set sources = array_append(r.sources, 'chain menu (official site)')")
w('    from _chain_targets t')
w("    where r.id = t.restaurant_id and not ('chain menu (official site)' = any (r.sources));")
w('')
w('    chain_id := c.chain_id; restaurants_matched := v_matched; restaurants_filled := v_filled; dishes_added := v_dishes;')
w('    return next;')
w('  end loop;')
w('end;')
w('$$;')
w('-- Only the team runs this from the SQL editor.')
w('revoke all on function public.apply_chain_menus(text) from public, anon, authenticated;')
w('')
w('commit;')

open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
print(f'wrote {os.path.relpath(OUT, ROOT)}: {len(chains)} chains ({len(with_data)} with allergen data), {len(dishes)} dishes')
