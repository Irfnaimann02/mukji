"""Build supabase/sql/046_chain_dish_english_names.sql from supabase/data/chains/*.json.

#126: 455 chain dishes had only a Korean name (name_en was a copy of name_ko), so
English users saw Korean at chain branches. The English names are now in the JSON
files (translated by the Mukji team, not the brands' official English). This writes
an SQL file that puts them in:
  - public.chain_menu_dishes (the team-only source table from 037), and
  - public.dishes rows that 037's apply_chain_menus() copied to branches
    (id = <restaurant_id>-chain-<chain_id>-<dish_no>).

Only names that are still a copy of the Korean name are changed, so an English name
someone already fixed by hand is never overwritten, and the file is safe to re-run.

Run from the repo root:  python scripts/chain_menus/build_046.py
"""

import glob
import json
import os

OUT = 'supabase/sql/046_chain_dish_english_names.sql'


def q(s):
    return "'" + s.replace("'", "''") + "'"


def chain_id(path):
    return os.path.splitext(os.path.basename(path))[0]


rows = []
for path in sorted(glob.glob('supabase/data/chains/*.json')):
    d = json.load(open(path, encoding='utf-8'))
    for n, dish in enumerate(d['dishes'], 1):
        en = (dish.get('name_en') or '').strip()
        if en and en != dish['name_ko']:
            rows.append((chain_id(path), n, dish['name_ko'], en))

lines = []
w = lines.append
w('-- 046_chain_dish_english_names.sql')
w('-- #126: English names for chain dishes that only had a Korean name.')
w('-- Generated by scripts/chain_menus/build_046.py from supabase/data/chains/*.json; do not edit by hand.')
w("-- The names were translated by the Mukji team; they are not the brands' official English.")
w('-- Changes only names that are still a copy of the Korean name, so it never overwrites a')
w('-- name fixed by hand, and it is safe to re-run.')
w('')
w('begin;')
w('')
w('create temp table _chain_names (chain_id text, dish_no int, name_ko text, name_en text) on commit drop;')
w('insert into _chain_names (chain_id, dish_no, name_ko, name_en) values')
w(',\n'.join(f'  ({q(c)}, {n}, {q(ko)}, {q(en)})' for c, n, ko, en in rows) + ';')
w('')
w('-- 1. the source table (037)')
w('update public.chain_menu_dishes cd')
w('   set name_en = v.name_en')
w('  from _chain_names v')
w(' where cd.chain_id = v.chain_id and cd.dish_no = v.dish_no')
w('   and cd.name_ko = v.name_ko')
w('   and (cd.name_en = cd.name_ko or btrim(coalesce(cd.name_en, \'\')) = \'\');')
w('')
w("-- 2. the dishes 037's apply_chain_menus() copied to each branch")
w('update public.dishes d')
w('   set name_en = v.name_en')
w('  from _chain_names v')
w(" where d.id like '%-chain-' || v.chain_id || '-' || v.dish_no")
w('   and d.name_ko = v.name_ko')
w("   and (d.name_en = d.name_ko or btrim(coalesce(d.name_en, '')) = '');")
w('')
w('commit;')
w('')
w('-- Check: no chain dish should still have its Korean name as the English name.')
w('--   select chain_id, count(*) from public.chain_menu_dishes where name_en = name_ko group by 1;')
w("--   select count(*) from public.dishes where id like '%-chain-%' and name_en = name_ko;")

open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print(f'{OUT}: {len(rows)} names')
